import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright';
import { readFile } from 'node:fs/promises';
import { generateKeyPairSync, sign } from 'node:crypto';
import { canonical } from '../src/protocol.mjs';
import { MAINNET_GENESIS_HASH, USDC_ASSET_ID, encodeAddress } from '../vendor/fairground/src/rails/algorand.ts';
const preview = spawn(process.execPath, ['tools/preview.mjs'], { stdio: ['ignore', 'pipe', 'pipe'] });
let browser;
try {
  await new Promise((resolve, reject) => { preview.stdout.once('data', resolve); preview.once('error', reject); setTimeout(() => reject(Error('Preview timed out')), 5000).unref(); });
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const external = [];
  await page.route('https://**/*', async route => {
    external.push(route.request().url());
    if (route.request().url().includes('/v2/accounts/')) return route.fulfill({ json: { assets: [{ 'asset-id': USDC_ASSET_ID, 'is-frozen': false }] } });
    return route.abort();
  });
  await page.goto('http://127.0.0.1:4199/');
  await page.getByText('Bundle verified', { exact: true }).waitFor();
  assert.equal(await page.locator('#file-count').textContent(), '5'); assert.equal(external.length, 0);
  await page.screenshot({ path: '/tmp/evolve-hosting-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Check mirrors', exact: true }).click();
  await page.getByText('Unavailable or reports a different release').first().waitFor();
  assert.equal(await page.locator('.mirror a').count(), 2);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: '/tmp/evolve-hosting-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.getByText('Verify your own release', { exact: true }).click();
  const original = JSON.parse(await readFile('public/demo.release.json', 'utf8')), corrupt = structuredClone(original);
  corrupt.assets[0].data = Buffer.from('changed').toString('base64');
  const originalId = await page.locator('#release-hash').textContent();
  await page.locator('#bundle').setInputFiles({ name: 'corrupt.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(corrupt)) });
  await page.getByRole('button', { name: 'Verify selected bundle', exact: true }).click();
  await page.getByText(/An asset differs/).waitFor(); assert.equal(await page.locator('#release-hash').textContent(), originalId);
  const keys = generateKeyPairSync('ed25519'), pem = keys.publicKey.export({ type: 'spki', format: 'pem' });
  await page.locator('#key').fill(pem);
  await page.locator('#bundle').setInputFiles({ name: 'release.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) });
  await page.getByRole('button', { name: 'Verify selected bundle', exact: true }).click();
  await page.getByText(/not signed by the supplied key/).waitFor();
  const fixture = structuredClone(original);
  fixture.manifest.project.name = '<img src=x onerror=alert(1)> Fixture';
  fixture.manifest.support.recipients.push({ ...fixture.manifest.support.recipients[0], id: 'operator', name: 'Fixture hosting operator', role: 'hosting', address: encodeAddress(new Uint8Array(32).fill(4)) });
  fixture.signature = sign(null, Buffer.from(canonical(fixture.manifest)), keys.privateKey).toString('base64');
  await page.locator('#bundle').setInputFiles({ name: 'fixture.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(fixture)) });
  await page.getByRole('button', { name: 'Verify selected bundle', exact: true }).click();
  await page.getByText('Signature and every public asset verified against the supplied publisher key.').waitFor();
  assert.equal(await page.locator('#project img').count(), 0);
  assert.equal(await page.locator('#recipients input[type=checkbox]:checked').count(), 0);
  await page.getByRole('checkbox', { name: 'EvolveTech development', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Fixture hosting operator', exact: true }).check();
  await page.getByRole('textbox', { name: 'USDC amount for EvolveTech development', exact: true }).fill('2');
  await page.getByRole('textbox', { name: 'USDC amount for Fixture hosting operator', exact: true }).fill('3');
  await page.getByRole('button', { name: 'Prepare wallet links', exact: true }).click();
  await page.locator('.wallet-link').nth(1).waitFor();
  assert.match(await page.locator('#payment-status').textContent(), /5.000000 USDC across 2/);
  let wrong = true;
  await page.route('https://**/v2/transactions/**', async route => {
    const cards = page.locator('.payment'), index = route.request().url().endsWith('B'.repeat(52)) ? 1 : 0;
    const link = await cards.nth(index).locator('.wallet-link').getAttribute('href'), url = new URL(link);
    const payment = { transaction: { id: index ? 'B'.repeat(52) : 'A'.repeat(52), sender: encodeAddress(new Uint8Array(32).fill(2)), 'genesis-hash': MAINNET_GENESIS_HASH, 'tx-type': 'axfer', 'confirmed-round': 100, 'round-time': Math.floor(Date.now() / 1000), note: Buffer.from(wrong ? 'wrong note' : url.searchParams.get('xnote')).toString('base64'), 'asset-transfer-transaction': { 'asset-id': USDC_ASSET_ID, receiver: fixture.manifest.support.recipients[index].address, amount: Number(url.searchParams.get('amount')) } } };
    return route.fulfill({ json: payment });
  });
  await page.getByRole('textbox', { name: 'Transaction ID for EvolveTech development', exact: true }).fill('A'.repeat(52));
  await page.getByRole('button', { name: 'Check receipt', exact: true }).first().click();
  await page.getByText(/payment note does not match/).waitFor();
  wrong = false;
  await page.getByRole('button', { name: 'Check receipt', exact: true }).first().click();
  await page.getByText(/Confirmed: asset, recipient/).first().waitFor();
  await page.getByRole('textbox', { name: 'Transaction ID for Fixture hosting operator', exact: true }).fill('B'.repeat(52));
  await page.getByRole('button', { name: 'Check receipt', exact: true }).nth(1).click();
  await page.getByText(/Confirmed: asset, recipient/).nth(1).waitFor();
  assert.equal(await page.locator('.wallet-link').count(), 0);
  await page.goto('http://127.0.0.1:4199/example/');
  await page.getByRole('textbox', { name: 'Add something to your list' }).fill('A browser-only task');
  await page.getByRole('button', { name: 'Add', exact: true }).click();
  await page.reload(); await page.getByText('A browser-only task', { exact: true }).waitFor();
  await page.getByRole('link', { name: /Inspect this release/ }).click(); await page.getByText('Bundle verified', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: signed example, mobile layout, corrupt imports, wrong signer, safe rendering, mirror failures, optional split donations, rejected/confirmed receipts, local app persistence and mirror portal. Payment reads used fixtures; no wallet was opened or funds sent.');
} finally { if (browser) await browser.close(); preview.kill('SIGTERM'); }
